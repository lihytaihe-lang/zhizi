"""Attribute each miss of an eval output: python3 attrib.py <shared Rime dir> <out.jsonl> [examples]
With an output written under ZHIZI_EVAL_TRACE it also says how far each miss got: on the first
page, generated by the whole-reading channel but not on the page, on Rime's next three pages, or
nowhere (the target was never produced).
first-page hit but not first -> pick (homophone/order); not on page ->
  whole: target is one dictionary entry; compose: dictionary words (>=2 chars) and single
  characters build it with no two singles in a row; phrase: needs two or more single
  characters in a row (a phrase missing from every layer); other: non-Chinese."""
import collections, glob, json, os, re, sys

shared, out = sys.argv[1], sys.argv[2]
show = int(sys.argv[3]) if len(sys.argv) > 3 else 8
words = set()
for path in glob.glob(os.path.join(shared, "*.dict.yaml")):
    body = open(path, encoding="utf-8").read().split("\n...\n", 1)
    for line in (body[1] if len(body) > 1 else "").splitlines():
        text = line.split("\t", 1)[0]
        if len(text) >= 2 and "\t" in line:
            words.add(text)
han = re.compile(r"^[一-鿿]+$")

def kind(target):
    if not han.match(target):
        return "other"
    if target in words or len(target) == 1:
        return "whole"
    n = len(target)
    # best[i] = fewest runs of consecutive single characters (then fewest pieces) up to i
    best = [(0, 0, False)] + [None] * n
    for i in range(n):
        if best[i] is None:
            continue
        runs, pieces, single = best[i]
        for j in range(i + 1, min(n, i + 8) + 1):
            piece = target[i:j]
            if j - i == 1:
                cand = (runs + (1 if single else 0), pieces + 1, True)
            elif piece in words:
                cand = (runs, pieces + 1, False)
            else:
                continue
            if best[j] is None or cand[:2] < best[j][:2]:
                best[j] = cand
    return "compose" if best[n][0] == 0 else "phrase"

rows = [json.loads(l) for l in open(out, encoding="utf-8")]
tally = collections.defaultdict(collections.Counter)
examples = collections.defaultdict(list)
for r in rows:
    if r["first"]:
        continue
    bucket = r.get("bucket", "all")
    k = "pick" if r["onPage"] else "miss-" + kind(r["target"])
    tally[bucket][k] += 1
    tally[bucket]["total"] += 1
    examples[k].append(f'{r["keys"]}→{r["target"]} (首:{r["page"][0] if r["page"] else ""})')
order = ["pick", "miss-whole", "miss-compose", "miss-phrase", "miss-other"]
print("bucket\tcases\tmisses\t" + "\t".join(order))
counts = collections.Counter(r.get("bucket", "all") for r in rows)
for bucket in sorted(tally):
    t = tally[bucket]
    print(f"{bucket}\t{counts[bucket]}\t{t['total']}\t" + "\t".join(f"{t[k]}" for k in order))
for k in order:
    if examples[k]:
        print(k, "e.g.", "；".join(examples[k][:show]))

if rows and "alternatives" in rows[0]:
    stage = collections.defaultdict(collections.Counter)
    stage_examples = collections.defaultdict(list)
    for r in rows:
        if r["first"]:
            continue
        if r["onPage"]:
            k = "on-page"
        elif r["target"] in r["alternatives"]:
            k = "generated-not-shown"
        elif r["onNextPages"]:
            k = "rime-next-pages"
        else:
            k = "never-produced"
        stage[r.get("bucket", "all")][k] += 1
        stage_examples[k].append(f'{r["keys"]}→{r["target"]} (首:{r["page"][0] if r["page"] else ""})')
    kinds = ["on-page", "generated-not-shown", "rime-next-pages", "never-produced"]
    print("\nbucket\t" + "\t".join(kinds))
    for bucket in sorted(stage):
        print(bucket + "\t" + "\t".join(str(stage[bucket][k]) for k in kinds))
    for k in kinds:
        if stage_examples[k]:
            print(k, "e.g.", "；".join(stage_examples[k][:show]))
