import { isTauriRuntime } from "./tauriRuntime";
export type LearningPreferences = { appLearning: boolean; projectLearning: boolean; secureInputLearning: false; updatedAtMs: number };
export type LearningCleanupPreview = { entryCount: number; entryIds: string[]; texts: string[] };
export type LearningCleanupResult = { batchId: string; deletedCount: number };
export type ModelAuditEvidence = { suggested: string; flagged: number; occurrences: number; avgMargin: number };
export type ModelAuditPair = ModelAuditEvidence & { pinyin: string; committed: string };
export type LearningCleanupList = { items: LearningCleanupItem[]; unmatchedModelAuditPairs: ModelAuditPair[] };
export type LearningCleanupItem = {
  id: string;
  text: string;
  pinyin: string;
  source: "sqlite_learned" | "rime_userdb";
  domain: string | null;
  learnedAtMs: number | null;
  lastHitAtMs: number | null;
  factoryTop1: string | null;
  displacedFactoryTop1: boolean;
  attribution: "learned-pollution" | "needs-context" | "abbrev-competition" | "dictionary-gap" | null;
  batchCleanupEligible: boolean;
  frictionEventCount: number;
  abandonedCount: number;
  deepPageCount: number;
  backspaceCount: number;
  suspected: boolean;
  modelAudit?: ModelAuditEvidence;
};
export type BackupPreview = { formatVersion: number; createdAtMs: number; lexiconCount: number; projectCount: number; dynamicSourceCount: number; knowledgeSourceCount: number; containsSecrets: false };
export type IntegrityReport = { quickCheck: string; foreignKeyErrors: number; schemaVersion: number; expectedSchemaVersion: number; lexiconCount: number; knowledgeChunkCount: number; recoveryContract: string };
export type ScaleProbeReport = { personalEntryCount: number; knowledgeChunkCount: number; personalQueryMilliseconds: number; knowledgeQueryMilliseconds: number; passed: boolean };
export type PersonalBlacklistItem = { id: string; reading: string; text: string };
async function invoke<T>(command: string, args?: Record<string, unknown>): Promise<T> { if (!isTauriRuntime()) throw new Error("此功能需要桌面管理台。"); const api = await import("@tauri-apps/api/core"); return api.invoke<T>(command, args); }
export const learningPreferences = () => invoke<LearningPreferences>("learning_preferences");
export const saveLearningPreferences = (preferences: LearningPreferences) => invoke<LearningPreferences>("save_learning_preferences", { preferences });
export const listLearningCleanupItems = () => invoke<LearningCleanupList>("list_learning_cleanup_items");
export const previewLearningCleanup = (ids: string[], domain: string | null) => invoke<LearningCleanupPreview>("preview_learning_cleanup", { ids, domain });
export const applyLearningCleanup = (ids: string[], domain: string | null) => invoke<LearningCleanupResult>("apply_learning_cleanup", { ids, domain });
export const undoLearningCleanup = (batchId: string) => invoke<number>("undo_learning_cleanup", { batchId });
export const exportMaintenanceBackup = () => invoke<string>("export_maintenance_backup");
export const previewMaintenanceBackup = (document: string) => invoke<BackupPreview>("preview_maintenance_backup", { document });
export const restoreMaintenanceBackup = (document: string) => invoke<BackupPreview>("restore_maintenance_backup", { document });
export const runIntegrityReport = () => invoke<IntegrityReport>("run_integrity_report");
export const runScaleProbe = () => invoke<ScaleProbeReport>("run_scale_probe");
export const listPersonalBlacklist = () => invoke<PersonalBlacklistItem[]>("list_personal_blacklist");
export const undoPersonalBlacklist = (ids: string[]) => invoke<number>("undo_personal_blacklist", { ids });
